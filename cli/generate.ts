type Check = { name: string; status: "ok" | "warn" | "fail"; detail: string };

/** The agent files match what nc generate would write; placeholders and unlisted role files are warnings. */
export function agentChecks(repo: string, home: string): Check[] {
  home = normHome(home);
  const tilde = (p: string) => (p.startsWith(home + "/") ? "~" + p.slice(home.length) : p);
  let cfg: Config;
  try {
    cfg = load(repo);
  } catch (e) {
    if (e instanceof ModelsError) return [];   // reported by the models.yaml check
    throw e;
  }
  const checks: Check[] = [];
  try {
    const p = plan(repo, home, cfg, undefined, false);   // MCP has a line of its own (mcpChecks)
    checks.push(
      p.actions.length
        ? { name: "agents", status: "fail", detail: `${p.actions.map((a) => `${a.verb} ${tilde(a.path)}`).join(", ")} – nc generate` }
        : { name: "agents", status: "ok", detail: `up to date: ${agentsLine(p, tilde)}` },
    );
    if (p.skipped.length)
      checks.push({ name: "agents (placeholder)", status: "warn", detail: `no OpenCode agent for ${p.skipped.map((s) => s.role).join(", ")}: the model of the class is a placeholder` });
  } catch (e) {
    if (!(e instanceof ModelsError)) throw e;
    checks.push({ name: "agents", status: "fail", detail: e.message });
  }
  const unlisted = unlistedRoleFiles(repo, cfg);
  if (unlisted.length)
    checks.push({ name: "roles without an entry", status: "warn", detail: `${unlisted.map((n) => `roles/${n}.md`).join(", ")} without an entry in roles (models.yaml) – no agent file` });
  return checks;
}

/** The MCP files match mcp/servers.yaml (direct only). Errors in servers.yaml show here, never on the agents line. */
export function mcpChecks(repo: string, home: string): Check[] {
  home = normHome(home);
  const tilde = (p: string) => (p.startsWith(home + "/") ? "~" + p.slice(home.length) : p);
  try {
    const m = planMcp(repo, home);
    if (m.actions.length)
      return [{ name: "MCP", status: "fail", detail: `outdated – nc generate (${m.actions.map((a) => `${a.verb} ${tilde(a.path)}`).join(", ")})` }];
    return [{ name: "MCP", status: "ok", detail: m.servers ? `up to date: ${m.servers}` : "no servers" }];
  } catch (e) {
    if (!(e instanceof ModelsError)) throw e;
    return [{ name: "MCP", status: "fail", detail: e.message }];
  }
}

/** Claude Code reads 0, false, no and off (any case) as off, like an empty value. */
const envOn = (v: string | undefined) => !!v && !["0", "false", "no", "off"].includes(v.toLowerCase());

/** Variables that override what models.yaml sets for Claude Code. CLAUDE_CODE_SUBAGENT_MODEL alone ranks below
 * the model field since 2.1.251 and needs no warning. Only the environment of this process: the env block of
 * ~/.claude/settings.json is not seen. */
export function claudeEnvChecks(): Check[] {
  const checks: Check[] = [];
  if (process.env.CLAUDE_CODE_EFFORT_LEVEL)
    checks.push({ name: "CLAUDE_CODE_EFFORT_LEVEL", status: "warn", detail: "set – overrides --effort, /effort and the effort field of the subagents" });
  if (envOn(process.env.CLAUDE_CODE_SUBAGENT_MODEL_FORCE))
    checks.push({ name: "CLAUDE_CODE_SUBAGENT_MODEL_FORCE", status: "warn", detail: "set – subagents ignore the model field and the model per call" });
  return checks;
}

/** Isolated (nc doctor in a task container): the agent folders nc-work mounts, named in NC_AGENTS
 * (`<claude>:<opencode>`, like NC_MEMORY_DIR). Real folders, read-only, only generated .md files. No comparison
 * of the content: in the container the snapshot's models.yaml holds, nc-work generates with the host checkout. */
export function agentChecksIsolated(): Check[] {
  const value = process.env.NC_AGENTS;
  if (!value)
    return [{ name: "agents", status: "warn", detail: "task without agent folders (made by an older nc-work) – create a new task for the roles" }];
  return value.split(":").map((dir, i): Check => {
    const name = `agents ${dir || "(empty)"}`;
    const st = dir ? lstat(dir) : null;
    if (!st) return { name, status: "fail", detail: "missing – nc-work did not mount the folder" };
    if (st.isSymbolicLink()) return { name, status: "fail", detail: "is a link – nc-work mounts a folder" };
    if (!st.isDirectory()) return { name, status: "fail", detail: "is not a folder" };
    try {
      accessSync(dir, constants.W_OK);
      return { name, status: "fail", detail: "writable – nc-work mounts it read-only" };
    } catch {}
    let files: string[];
    try {
      files = readdirSync(dir).filter((n) => n.endsWith(".md")).sort();
    } catch (e: any) {
      return { name, status: "fail", detail: `not readable (${e?.code ?? e})` };
    }
    const foreign = files.filter((n) => !isGenerated(join(dir, n)));
    if (foreign.length) return { name, status: "fail", detail: `without the GENERATED line: ${foreign.join(", ")}` };
    if (!files.length && i === 1)
      return { name, status: "warn", detail: "empty – generating at the start failed, or every OpenCode role is blocked here" };
    return { name, status: "ok", detail: `read-only, ${files.length} generated file(s)` };
  });
}
