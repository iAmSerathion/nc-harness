/**
 * nc generate – agent files for Claude Code and OpenCode from roles/ and models.yaml.
 *
 *   nc generate          write ~/.claude/agents/<role>.md and <OpenCode config dir>/agents/<role>.md
 *   nc generate --check  write nothing, name per file what a run would do; exit 0 if nothing, else 1
 *   nc generate --out DIR --path PROJECT [--check]
 *                        for a task container (nc-work, before every session start): DIR/claude/<role>.md and
 *                        DIR/opencode/<role>.md, with the policy of the host folder PROJECT. DIR belongs to
 *                        nc-work: a .md without the GENERATED line or a subfolder is exit 2, no backups.
 *
 * Exit 2: broken models.yaml or role file (then no file is touched: everything is checked and computed first),
 * a target folder that is a link or lies in the repo, a foreign entry in an --out folder, a write error, a
 * wrong call, a call inside a task container.
 *
 * A generated file has exactly GENERATED as its second line (the first stays `---`, or neither runtime reads
 * it). Generated files without a role are removed; a foreign file of the same name is moved to
 * ~/.nc/backup/<date>/ first (the rule of move_aside in install.sh); other foreign files stay. Files are
 * written through a temporary name that does not end in .md and renamed: both runtimes load every .md at once.
 *
 * The files in the home folder hold in every folder, so without --out no policy is applied (nc models check
 * --host does not see them either). With --out the policy of --path decides which OpenCode roles
 * get a file. No silent fallback: a role whose class model is a placeholder (or, with --path, refused there)
 * gets no OpenCode file, and an old one is removed. Every written file is 0644 whatever the umask: the user in
 * the container is a subuid on the host and reads only what "others" may read.
 *
 * Claude Code is the only orchestrator; OpenCode only gets the worker subagents (a generated orchestrator.md of
 * an older run has no role any more and is removed like any generated file without one). On the host (never with
 * --out) the MCP configuration from mcp/servers.yaml as well: <OpenCode config dir>/opencode.jsonc (first line GENERATED as a
 * // comment) and ~/.nc/mcp/claude.json (the harness' own folder: no header, no backup). With --out servers.yaml is
 * not even opened, so a broken file never stops a session start in a task.
 */
import { accessSync, chmodSync, constants, cpSync, lstatSync, mkdirSync, readdirSync, readFileSync, realpathSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, isAbsolute, join, resolve } from "node:path";
import { claudeMcpFile, loadServers, MCP_GENERATED, type McpServer, opencodeMcpFile } from "./mcp.ts";
import { mode, ncHome, opencodeConfigDir } from "./mode.ts";
import { classStatus, type Config, load, ModelsError, policyAt, ROLE_NAME } from "./models.ts";

export const GENERATED = "# GENERATED by nc-harness – do not edit by hand";
/** Read-only roles in Claude Code: an allow list. disallowedTools would keep Agent (start a writing subagent),
 * Monitor (runs commands) and MCP tools, and on Linux Grep and Glob only come through a tools field. */
const READ_TOOLS = "Read, Grep, Glob";
/** Only the researcher gets web tools: planner and reviewer judge local code, and web content in a reviewer is an injection path. */
const WEB_ROLE = "researcher";
const readTools = (role: string) => (role === WEB_ROLE ? `${READ_TOOLS}, WebFetch, WebSearch` : READ_TOOLS);
/** One OpenCode permission rule; `effect` is what the rule does when it is the last one that matches. */
type Rule = { action: string; resource: string; effect: "deny" | "ask" | "allow" };
/** Read-only roles in OpenCode. Without subagent a reader could start a writing subagent. `*_*`: the action of an MCP
 * tool is `<server>_<tool>` (OpenCode 2.2.7 matches actions with wildcards), so this keeps every
 * MCP tool, the MCP resource tools (opencode_*) and the built-in artifact_* and schedule_* tools from readers. */
const READ_DENY = ["edit", "shell", "subagent", "*_*"];
/** `*_*` also matches the built-in actions external_directory (reading outside the project) and doom_loop, whose
 * default is ask. The last matching rule wins, so these rules come after `*_*` and restore that default. */
const READ_RESTORE = ["external_directory", "doom_loop"];
const READ_RULES: Rule[] = [
  ...READ_DENY.map((action) => ({ action, resource: "*", effect: "deny" as const })),
  ...READ_RESTORE.map((action) => ({ action, resource: "*", effect: "ask" as const })),
];
const ROLE_KEYS = ["name", "description", "access"];

type Role = { name: string; description: string; access: "read" | "write"; body: string };
export type Action = { verb: "create" | "replace" | "back up" | "remove"; path: string; content?: string; backup?: string };
export type Plan = {
  actions: Action[];   // agent files
  mcp: Action[];       // MCP files (host only; empty with --out)
  mcpServers: number;
  skipped: { role: string; reason: string }[];
  dirs: { claude: string; opencode: string };
  counts: { claude: number; opencode: number };
};
/** --out DIR --path PROJECT: the folder nc-work mounts into a task container, and the host folder of its project. */
export type Out = { out: string; path: string };
/** Our own temporary files (write() below), e.g. left by an interrupted run. */
const TMP = /^\..+\.nc-tmp-\d+$/;

const q = (v: unknown) => JSON.stringify(v) ?? String(v);

/** roles/<name>.md: frontmatter with name (= file name), description, access (read | write); the body is the prompt. */
export function readRole(repo: string, name: string): Role {
  const file = `roles/${name}.md`;
  const bad = (msg: string): never => {
    throw new ModelsError(`${file}: ${msg}`);
  };
  let text: string;
  try {
    text = readFileSync(join(repo, file), "utf8");
  } catch (e: any) {
    return bad(`not readable (${e?.code ?? e})`);
  }
  const m = text.match(/^---\n([\s\S]*?)\n---[ \t]*(?:\n|$)([\s\S]*)$/);
  if (!m) return bad("no frontmatter (first line ---, then the fields, then ---)");
  let fm: any;
  try {
    fm = Bun.YAML.parse(m[1]);
  } catch (e: any) {
    return bad(`frontmatter is not valid YAML (${String(e?.message ?? e).split("\n")[0]})`);
  }
  if (!fm || typeof fm !== "object" || Array.isArray(fm)) return bad("frontmatter is not a mapping");
  const unknown = Object.keys(fm).filter((k) => !ROLE_KEYS.includes(k));
  if (unknown.length) bad(`unknown field ${q(unknown[0])} (allowed: ${ROLE_KEYS.join(", ")}; the class is in models.yaml)`);
  if (typeof fm.name !== "string" || !ROLE_NAME.test(fm.name)) bad(`name ${q(fm.name)} does not have the form ${ROLE_NAME.source}`);
  if (fm.name !== name) bad(`name ${q(fm.name)} is not the file name ${q(name)}`);
  if (typeof fm.description !== "string" || !fm.description.trim()) bad("description missing or empty");
  if (fm.access !== "read" && fm.access !== "write") bad(`access is ${q(fm.access)}, allowed: read, write`);
  return { name, description: fm.description.trim(), access: fm.access, body: m[2].replace(/^\n+/, "").replace(/\s*$/, "\n") };
}

/** A model ID as a plain YAML scalar where that is safe (as OpenCode's docs write it), else quoted. */
const scalar = (v: string) => (/^[A-Za-z0-9][A-Za-z0-9._\/:@~+-]*(#[a-z0-9._-]+)?$/.test(v) ? v : q(v));

function claudeFile(r: Role, s: { model: string; effort: string }): string {
  return [
    "---",
    GENERATED,
    `name: ${r.name}`,
    `description: ${q(r.description)}`,
    `model: ${s.model}`,
    `effort: ${s.effort}`,   // always: a subagent on another model than the session does not inherit its effort
    ...(r.access === "read" ? [`tools: ${readTools(r.name)}`] : []),
    "---",
    r.body,
  ].join("\n");
}

const permissions = (rules: Rule[]) => [
  "permissions:",
  ...rules.flatMap((r) => [`  - action: ${scalar(r.action)}`, `    resource: ${q(r.resource)}`, `    effect: ${r.effect}`]),
];

function opencodeFile(r: Role, model: string, steps: number | null): string {
  return [
    "---",
    GENERATED,
    `description: ${q(r.description)}`,
    "mode: subagent",
    "hidden: false",     // else a project file of the same name could hide the role (/etc/opencode only fixes what is set here)
    "disabled: false",   // makes the file a version 2 file for sure
    `model: ${scalar(model)}`,
    ...(steps === null ? [] : [`steps: ${steps}`]),   // caps the agent loop (OpenCode 2.2.7 AgentConfig.steps)
    ...(r.access === "read" ? permissions(READ_RULES) : []),
    "---",
    r.body,
  ].join("\n");
}

function lstat(path: string) {
  try {
    return lstatSync(path);
  } catch {
    return null;
  }
}

/** A regular file with the marker of its type: an agent .md has exactly GENERATED as its second line (the first
 * stays `---`), a .jsonc has exactly MCP_GENERATED as its first. Links, folders and everything else are foreign. */
export function isGenerated(path: string): boolean {
  if (!lstat(path)?.isFile()) return false;
  try {
    const lines = readFileSync(path, "utf8").split("\n");
    return path.endsWith(".jsonc")
      ? lines[0] === MCP_GENERATED
      : lines[1] === GENERATED;
  } catch {
    return false;
  }
}

const pad2 = (n: number) => String(n).padStart(2, "0");

/** Where install.sh's move_aside would put this path: ~/.nc/backup/<date>/<path below HOME>, with the time on a collision. */
function backupPath(home: string, path: string): string {
  const now = new Date();
  const day = `${now.getFullYear()}-${pad2(now.getMonth() + 1)}-${pad2(now.getDate())}`;
  const rel = path.startsWith(home + "/") ? path.slice(home.length + 1) : path.replace(/^\/+/, "");
  const dest = join(ncHome(home), "backup", day, rel);
  return lstat(dest) ? `${dest}.${pad2(now.getHours())}${pad2(now.getMinutes())}${pad2(now.getSeconds())}` : dest;
}

/** The nearest existing folder at or above dir lies in the repo, through links too (inside_repo in install.sh). */
function insideRepo(dir: string, repo: string): boolean {
  let d = dir;
  for (;;) {
    try {
      if (statSync(d).isDirectory()) break;
    } catch {}
    if (dirname(d) === d) return false;
    d = dirname(d);
  }
  try {
    const real = realpathSync(d), top = realpathSync(repo);
    return real === top || real.startsWith(top + "/");
  } catch {
    return false;
  }
}

/** The target folder: missing is fine (created on write); a link, a non-folder or a folder in the repo is exit 2. */
function targetDir(dir: string, repo: string, tilde: (p: string) => string): string {
  const st = lstat(dir);
  if (st?.isSymbolicLink()) throw new ModelsError(`${tilde(dir)} is a link – nc generate does not write through a link; remove or replace it by hand`);
  if (st && !st.isDirectory()) throw new ModelsError(`${tilde(dir)} is not a folder`);
  if (insideRepo(dir, repo)) throw new ModelsError(`${tilde(dir)} lies in the repo – nc generate does not write into the repo; check HOME, XDG_CONFIG_HOME and OPENCODE_CONFIG_DIR`);
  return dir;
}

/** HOME without a trailing slash or dots, so paths below it are found (backup path, ~ in messages). */
const normHome = (home: string) => (isAbsolute(home) ? resolve(home) : home);

/** Everything a run would do. Throws ModelsError (exit 2) before anything is written. withMcp: also the MCP files
 * (never with --out; nc doctor checks them on a line of their own). */
export function plan(repo: string, home: string, cfg: Config = load(repo), out?: Out, withMcp = !out): Plan {
  if (!isAbsolute(home)) throw new ModelsError(`HOME is ${home ? "not an absolute path" : "empty"}`);
  home = resolve(home);   // HOME=/home/me/ would put the backup under <date>/home/me/.claude/…
  const tilde = (p: string) => (p.startsWith(home + "/") ? "~" + p.slice(home.length) : p);
  const dirs = out
    ? { claude: targetDir(join(out.out, "claude"), repo, tilde), opencode: targetDir(join(out.out, "opencode"), repo, tilde) }
    : { claude: targetDir(join(home, ".claude", "agents"), repo, tilde), opencode: targetDir(join(opencodeConfigDir(home), "agents"), repo, tilde) };
  const pol = out ? policyAt(cfg, out.path) : null;
  const actions: Action[] = [];
  if (out) {
    // The folder belongs to nc-work: anything foreign in it is a mistake to look at, not to back up or overwrite.
    for (const dir of [dirs.claude, dirs.opencode]) {
      let names: string[] = [];
      try {
        names = readdirSync(dir).sort();
      } catch {}
      for (const n of names) {
        const path = join(dir, n);
        const foreign = () => new ModelsError(`${tilde(path)} is not a generated file – the folder belongs to nc-work; remove it by hand`);
        // A folder first, also through a link (both runtimes read agent folders recursively), even one named like a leftover.
        const st = lstat(path);
        let folder = !!st?.isDirectory();
        if (st?.isSymbolicLink()) {
          try {
            folder = statSync(path).isDirectory();
          } catch {}
        }
        if (folder) throw foreign();
        if (TMP.test(n)) {   // left by an interrupted run; nc-work runs one generation per task at a time (lock)
          actions.push({ verb: "remove", path });
          continue;
        }
        if (n.endsWith(".md") && !isGenerated(path)) throw foreign();
      }
    }
  }
  const roles = new Map<string, Role>();
  const role = (name: string) => roles.get(name) ?? roles.set(name, readRole(repo, name)).get(name)!;
  const want = new Map<string, string>();   // path -> content
  for (const [name, s] of Object.entries(cfg.claudeSubagents)) want.set(join(dirs.claude, `${name}.md`), claudeFile(role(name), s));
  const skipped: Plan["skipped"] = [];
  let opencode = 0;
  for (const [name, s] of Object.entries(cfg.opencodeSubagents)) {
    const r = role(name);   // checked even when skipped: a broken role file is exit 2 either way
    const k = cfg.roles[name];
    const cls = cfg.classes[k];
    if (cls.placeholder) {
      skipped.push({ role: name, reason: `the model of class ${k} is a placeholder (TODO in models.yaml) – no OpenCode agent, no other model instead` });
      continue;
    }
    const st = pol ? classStatus(cfg, pol, k) : null;
    if (st && !st.allowed) {
      skipped.push({ role: name, reason: `class ${k} not allowed in ${out!.path}: ${st.reason} – no OpenCode agent` });
      continue;
    }
    want.set(join(dirs.opencode, `${name}.md`), opencodeFile(r, s.variant ? `${cls.model}#${s.variant}` : cls.model!, s.steps));
    opencode++;
  }
  for (const [path, content] of want) {
    const st = lstat(path);
    if (!st) actions.push({ verb: "create", path, content });
    else if (!isGenerated(path)) actions.push({ verb: "back up", path, content, backup: backupPath(home, path) });   // never with --out (checked above)
    else if (readFileSync(path, "utf8") !== content) actions.push({ verb: "replace", path, content });
  }
  for (const dir of [dirs.claude, dirs.opencode]) {
    let names: string[] = [];
    try {
      names = readdirSync(dir).filter((n) => n.endsWith(".md")).sort();
    } catch {}
    for (const n of names) {
      const path = join(dir, n);
      if (!want.has(path) && isGenerated(path)) actions.push({ verb: "remove", path });
    }
  }
  const m = withMcp ? planMcp(repo, home) : { actions: [], servers: 0 };
  return { actions, mcp: m.actions, mcpServers: m.servers, skipped, dirs, counts: { claude: Object.keys(cfg.claudeSubagents).length, opencode } };
}

/** Where the MCP files go on the host. ~/.nc/mcp belongs to the harness alone. */
export const mcpTargets = (home: string) => ({ claude: join(home, ".nc", "mcp", "claude.json"), opencode: join(opencodeConfigDir(home), "opencode.jsonc") });

/** The MCP files from mcp/servers.yaml (host only). servers: {} writes nothing and removes old generated files.
 * A foreign opencode.jsonc is backed up before it is replaced and left alone otherwise. Throws ModelsError (exit 2). */
export function planMcp(repo: string, home: string, servers: McpServer[] = loadServers(repo)): { actions: Action[]; servers: number } {
  home = resolve(home);
  const tilde = (p: string) => (p.startsWith(home + "/") ? "~" + p.slice(home.length) : p);
  const t = mcpTargets(home);
  targetDir(dirname(t.claude), repo, tilde);
  targetDir(dirname(t.opencode), repo, tilde);
  const actions: Action[] = [];
  const want = servers.length ? { claude: claudeMcpFile(servers), opencode: opencodeMcpFile(servers) } : null;
  const read = (path: string) => {
    try {
      return readFileSync(path, "utf8");
    } catch (e: any) {
      throw new ModelsError(`${tilde(path)} not readable (${e?.code ?? e})`);
    }
  };

  const oc = lstat(t.opencode);
  if (want) {
    if (!oc) actions.push({ verb: "create", path: t.opencode, content: want.opencode });
    else if (!isGenerated(t.opencode)) actions.push({ verb: "back up", path: t.opencode, content: want.opencode, backup: backupPath(home, t.opencode) });
    else if (read(t.opencode) !== want.opencode) actions.push({ verb: "replace", path: t.opencode, content: want.opencode });
  } else if (oc && isGenerated(t.opencode)) actions.push({ verb: "remove", path: t.opencode });

  const cl = lstat(t.claude);
  if (cl && !cl.isFile()) throw new ModelsError(`${tilde(t.claude)} is not a file – the folder belongs to nc-harness; remove it by hand`);
  if (want) {
    if (!cl) actions.push({ verb: "create", path: t.claude, content: want.claude });
    else if (read(t.claude) !== want.claude) actions.push({ verb: "replace", path: t.claude, content: want.claude });
  } else if (cl) actions.push({ verb: "remove", path: t.claude });
  return { actions, servers: servers.length };
}

const agentsLine = (p: Plan, tilde: (p: string) => string) =>
  `${tilde(p.dirs.claude)} (${p.counts.claude}), ${tilde(p.dirs.opencode)} (${p.counts.opencode})`;

/** Files in roles/ without an entry in roles (models.yaml): no agent file is generated for them. */
export function unlistedRoleFiles(repo: string, cfg: Config): string[] {
  let names: string[] = [];
  try {
    names = readdirSync(join(repo, "roles")).filter((n) => n.endsWith(".md"));
  } catch {}
  return names.map((n) => n.slice(0, -3)).filter((n) => !Object.hasOwn(cfg.roles, n)).sort();
}

function moveAside(path: string, dest: string) {
  mkdirSync(dirname(dest), { recursive: true });
  try {
    renameSync(path, dest);
  } catch (e: any) {
    if (e?.code !== "EXDEV") throw e;
    cpSync(path, dest, { recursive: true, verbatimSymlinks: true });
    rmSync(path, { recursive: true, force: true });
  }
}

function write(path: string, content: string) {
  mkdirSync(dirname(path), { recursive: true });
  const tmp = join(dirname(path), `.${basename(path)}.nc-tmp-${process.pid}`);   // not *.md: never loaded half-written
  try {
    writeFileSync(tmp, content);
    chmodSync(tmp, 0o644);   // whatever the umask: the container user reads as "other"
    renameSync(tmp, path);
  } catch (e) {
    rmSync(tmp, { force: true });
    throw e;
  }
}

const PAST = { create: "created", replace: "replaced", "back up": "backed up", remove: "removed" };
const say = (verb: string, detail: string) => console.log(`  ${verb.padEnd(10)} ${detail}`);

const USAGE = "nc generate [--check] | nc generate --out DIR --path PROJECT_PATH [--check]";

/** --check, --out DIR, --path PROJECT (also --x=value). Throws ModelsError for a wrong call. */
function parseArgs(args: string[]): { check: boolean; out?: Out } {
  let check = false;
  const v: Record<string, string> = {};
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a === "--check") {
      if (check) throw new ModelsError(`--check given twice (${USAGE})`);
      check = true;
      continue;
    }
    const m = a.match(/^--(out|path)(?:=(.*))?$/s);
    if (!m) throw new ModelsError(`unknown argument ${q(a)} (${USAGE})`);
    const key = m[1];
    const value = m[2] ?? args[++i];
    if (key in v) throw new ModelsError(`--${key} given twice (${USAGE})`);
    if (value === undefined || value === "") throw new ModelsError(`--${key} needs a value (${USAGE})`);
    if (!isAbsolute(value)) throw new ModelsError(`--${key} ${q(value)} is not an absolute path`);
    v[key] = value;
  }
  if (("out" in v) !== ("path" in v)) throw new ModelsError(`--out and --path only together (${USAGE})`);
  return { check, out: "out" in v ? { out: resolve(v.out), path: v.path } : undefined };
}

export function generate(repo: string, home: string, args: string[]): number {
  const fail = (msg: string) => {
    process.stderr.write(`nc generate: ${msg}\n`);
    return 2;
  };
  if (mode() === "isolated")
    return fail("not in a task container – nc-work generates the agent files on the host before every session start; there is no MCP in the container");
  let check: boolean, out: Out | undefined;
  try {
    ({ check, out } = parseArgs(args));
  } catch (e: any) {
    return fail(e.message);
  }
  home = normHome(home);
  const tilde = (p: string) => (p.startsWith(home + "/") ? "~" + p.slice(home.length) : p);

  let p: Plan;
  try {
    p = plan(repo, home, load(repo), out);
  } catch (e: any) {
    return fail(e instanceof ModelsError ? e.message : `unexpected error: ${e?.message ?? e}`);
  }
  for (const s of p.skipped) say("skipped", `OpenCode agent ${s.role}: ${s.reason}`);
  if (out && !check) {
    // The two folders are mounted into running containers: created when missing, never replaced or removed.
    try {
      for (const dir of [p.dirs.claude, p.dirs.opencode]) {
        mkdirSync(dir, { recursive: true });
        chmodSync(dir, 0o755);
      }
    } catch (e: any) {
      return fail(`${e?.code ?? ""} ${e?.message ?? e}`.replace(/\s+/g, " ").trim());
    }
  }
  const all = [...p.actions, ...p.mcp];
  if (!all.length) {
    say("ok", `agents up to date: ${agentsLine(p, tilde)}`);
    if (!out) say("ok", `MCP up to date: ${p.mcpServers ? `${p.mcpServers} server(s)` : "no servers"}`);
    return 0;
  }
  if (check) {
    for (const a of all) say(a.verb, tilde(a.path) + (a.backup ? ` -> ${tilde(a.backup)}` : ""));
    return 1;
  }
  for (const a of all) {
    try {
      if (a.verb === "remove") rmSync(a.path, { force: true });   // force: gone meanwhile is fine; parallel runs on one folder are not supported (nc-work locks)
      else {
        if (a.verb === "back up") {
          moveAside(a.path, a.backup!);
          say(PAST["back up"], `${tilde(a.path)} -> ${tilde(a.backup!)}`);
        }
        write(a.path, a.content!);
      }
    } catch (e: any) {
      return fail(`${tilde(a.path)}: ${e?.code ?? ""} ${e?.message ?? e}`.replace(/\s+/g, " ").trim() + " – run nc generate again once it is fixed");
    }
    say(a.verb === "back up" ? PAST.create : PAST[a.verb], tilde(a.path));
  }
  return 0;
}

