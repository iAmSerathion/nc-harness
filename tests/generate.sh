#!/usr/bin/env bash
# Tests for nc generate: agent files for Claude Code and OpenCode from roles/ and models.yaml, and the
# MCP files from mcp/servers.yaml.
# No network, no keys, throwaway $HOME, own models.yaml and roles/ in a copy of the repo.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
BUN_DIR="$(dirname "$(mise which bun 2>/dev/null || command -v bun)")"
unset NC_HARNESS_VERSION NC_PROJECT_PATH NC_OPENCODE NC_SECRETS OPENROUTER_API_KEY XDG_CONFIG_HOME OPENCODE_CONFIG_DIR \
  NC_MEMORY_DIR NC_MEMORY_OUTBOX NC_PROJECT NC_HOME GH_TOKEN GITHUB_TOKEN \
  CLAUDE_CODE_EFFORT_LEVEL CLAUDE_CODE_SUBAGENT_MODEL CLAUDE_CODE_SUBAGENT_MODEL_FORCE || true
export BUN_RUNTIME_TRANSPILER_CACHE_PATH=0   # no Bun cache anywhere
export NC_MACHINE=server                     # the expectations below are the server's, also when run on a Mac

T="$(mktemp -d)"                     # two steps: inside one $(…) a failed mktemp would leave T = the start folder
T="$(cd "$T" && pwd -P)"             # real path: on macOS /tmp is itself a link
trap 'chmod -R u+rwX "$T" 2>/dev/null; rm -rf "$T"' EXIT
mkdir "$T/cwd" && cd "$T/cwd"        # a neutral current folder
export HOME="$T/home"
ALL_PATH="$BUN_DIR:$PATH"
BASE_PATH="$(IFS=:; for d in $ALL_PATH; do [ -x "$d/nc-work" ] || printf '%s:' "$d"; done)"
export PATH="$HOME/.local/bin:${BASE_PATH%:}"
command -v bun > /dev/null || { echo "FAIL: bun not on the test PATH" >&2; exit 1; }
! command -v nc-work > /dev/null || { echo "FAIL: nc-work still on the test PATH" >&2; exit 1; }

pass=0
fail() { echo "FAIL: $*" >&2; exit 1; }
ok()   { echo "ok   $*"; pass=$((pass + 1)); }
RC="$T/repo"                                  # copy of the repo whose models.yaml and roles/ the tests replace
cp -a "$REPO" "$RC" && rm -rf "$RC/.git"
nc()   { "$RC/bin/nc" "$@"; }
expect() {  # expect <exit code> <pattern on stdout+stderr, or ''> <command…>; leaves stdout in $T/out, stderr in $T/err
  local want="$1" pat="$2" code=0; shift 2
  "$@" > "$T/out" 2> "$T/err" || code=$?
  [ "$code" = "$want" ] || fail "exit $code, expected $want: $* – $(cat "$T/out" "$T/err")"
  [ -z "$pat" ] || cat "$T/out" "$T/err" | grep -q -- "$pat" || fail "$*: expected '$pat', got: $(cat "$T/out" "$T/err")"
}
r() {  # r <text> <old> <new>: the first old replaced; ${s/"$old"/"$new"} would keep the quotes in bash 3.2 (macOS)
  local s="$1" old="$2" new="$3"; [[ "$s" == *"$old"* ]] || fail "fixture: '$old' not found"
  printf '%s%s%s' "${s%%"$old"*}" "$new" "${s#*"$old"}"
}
is() { [ "$1" = "$2" ] || fail "$3: got [$1], expected [$2]"; }
inode() { stat -c %i "$1" 2>/dev/null || stat -f %i "$1"; }
line() { sed -n "${2}p" "$1"; }
# The marker as text, not taken from the code: a changed marker must fail here.
GEN='# GENERATED by nc-harness – do not edit by hand'
TODAY="$(date +%F)"
CA="$HOME/.claude/agents"
OA="$HOME/.config/opencode/agents"

FREE='"openrouter/acme/tiny-1:free"'
CC='claude_code:
  orchestrator: { model: opus, effort: high }
  subagents:
    planner:     { model: opus,   effort: high }
    reviewer:    { model: opus,   effort: xhigh }
    implementer: { model: sonnet, effort: medium }
    tester:      { model: haiku,  effort: low }
    researcher:  { model: haiku,  effort: medium }'
OC='opencode:
  subagents:
    implementer: { variant: high }
    tester:      { variant: low }
    researcher:  {}'
yaml() {  # yaml [extra text]: models.yaml from FREE, CC, OC and the extra text
  cat > "$RC/models.yaml" <<EOF
allow_headless_claude: false
classes:
  frontier: { runtime: claude-code }
  standard: { runtime: opencode, model: "openrouter/acme/big-1" }
  cheap:    { runtime: opencode, model: "openrouter/acme/small-1" }
  free:     { runtime: opencode, model: $FREE }
roles: { planner: frontier, reviewer: frontier, implementer: standard, tester: cheap, researcher: free }
policies:
  - match: "~/projects/acme/**"
    deny_classes: [free]
    isolation: container
  - match: "**"
$CC
$OC
${1:-}
EOF
}
yaml
mkdir -p "$HOME/projects/acme/website" "$HOME/sandbox"

# 1. five Claude files and three OpenCode files with the values set (OpenCode: hidden: false)
expect 0 "" nc generate
for r in planner reviewer implementer tester researcher; do
  f="$CA/$r.md"
  [ -f "$f" ] || fail "no Claude file for $r"
  is "$(line "$f" 1)" "---" "first line of $f"
  is "$(line "$f" 2)" "$GEN" "second line of $f"
  grep -qx "name: $r" "$f" || fail "$f: no name: $r"
  grep -q '^description: "' "$f" || fail "$f: no description"
done
for r in implementer tester researcher; do
  f="$OA/$r.md"
  is "$(line "$f" 1)" "---" "first line of $f"
  is "$(line "$f" 2)" "$GEN" "second line of $f"
  grep -qx "mode: subagent" "$f" && grep -qx "hidden: false" "$f" && grep -qx "disabled: false" "$f" || fail "$f: mode, hidden or disabled missing"
  grep -q "^name:" "$f" && fail "$f has a name key"
  true
done
[ ! -e "$OA/planner.md" ] && [ ! -e "$OA/reviewer.md" ] || fail "planner or reviewer got an OpenCode file"
is "$(ls "$CA" | wc -l | tr -d ' ')" 5 "files in ~/.claude/agents"
is "$(ls "$OA" | wc -l | tr -d ' ')" 3 "files in the OpenCode agents folder"
is "$(grep -E '^(model|effort):' "$CA/planner.md" | tr '\n' ' ')" "model: opus effort: high " "planner"
is "$(grep -E '^(model|effort):' "$CA/reviewer.md" | tr '\n' ' ')" "model: opus effort: xhigh " "reviewer"
is "$(grep -E '^(model|effort):' "$CA/implementer.md" | tr '\n' ' ')" "model: sonnet effort: medium " "implementer"
is "$(grep -E '^(model|effort):' "$CA/tester.md" | tr '\n' ' ')" "model: haiku effort: low " "tester"
is "$(grep '^model:' "$OA/implementer.md")" "model: openrouter/acme/big-1#high" "OpenCode implementer"
is "$(grep '^model:' "$OA/tester.md")" "model: openrouter/acme/small-1#low" "OpenCode tester"
is "$(grep '^model:' "$OA/researcher.md")" "model: openrouter/acme/tiny-1:free" "OpenCode researcher (no variant)"
grep -q "You take care of tests" "$CA/tester.md" && grep -q "You take care of tests" "$OA/tester.md" || fail "role text missing"
ok "five Claude and three OpenCode files: ---, the GENERATED line, hidden: false, disabled: false, no name in OpenCode, exact model lines"

# 2. read-only roles: the tools line in Claude Code, four denials and two ask rules in OpenCode; write roles neither
DENY='permissions:
  - action: edit
    resource: "*"
    effect: deny
  - action: shell
    resource: "*"
    effect: deny
  - action: subagent
    resource: "*"
    effect: deny
  - action: "*_*"
    resource: "*"
    effect: deny
  - action: external_directory
    resource: "*"
    effect: ask
  - action: doom_loop
    resource: "*"
    effect: ask'
for r in planner reviewer researcher; do
  want="tools: Read, Grep, Glob"; [ "$r" = researcher ] && want="tools: Read, Grep, Glob, WebFetch, WebSearch"   # only the researcher reads the web
  is "$(grep '^tools:' "$CA/$r.md")" "$want" "tools of $r"
done
for r in implementer tester; do
  grep -qE "^tools:|^disallowedTools:" "$CA/$r.md" && fail "write role $r has a tools line"
  grep -q "permissions" "$OA/$r.md" && fail "write role $r has permissions"
done
is "$(sed -n '/^permissions:/,/^---$/p' "$OA/researcher.md" | sed '$d')" "$DENY" "denials of the researcher"
# *_* also matches external_directory and doom_loop; the last matching rule wins, so their ask rules must come after it
wild="$(grep -n '^  - action: "\*_\*"$' "$OA/researcher.md" | cut -d: -f1)"
for a in external_directory doom_loop; do
  n="$(grep -n "^  - action: $a\$" "$OA/researcher.md" | cut -d: -f1)"
  [ -n "$wild" ] && [ -n "$n" ] && [ "$n" -gt "$wild" ] || fail "$a has no rule after *_* (lines: *_* '$wild', $a '$n')"
  [ "$(sed -n "$((n + 2))p" "$OA/researcher.md")" = "    effect: ask" ] || fail "$a after *_* is not ask"
done
ok "read-only roles get exactly the tools line, the four denials (edit, shell, subagent, MCP tools *_*) and after *_* ask for external_directory and doom_loop, write roles neither"

# 3. a second run writes nothing (same inodes), no temporary files are left
before="$(for f in "$CA"/* "$OA"/*; do inode "$f"; done)"
expect 0 "agents up to date" nc generate
is "$(for f in "$CA"/* "$OA"/*; do inode "$f"; done)" "$before" "inodes after a second run"
is "$(ls -A "$CA" "$OA" | grep -v '\.md$' | grep -v '^$' | grep -v ':$' || true)" "" "temporary files"
expect 0 "" nc generate --check
ok "a second run rewrites no file, no temporary file stays, --check is exit 0"

# 4. --check after changes: models.yaml, a role file, a generated file by hand; nothing is written
CC="$(r "$CC" "tester:      { model: haiku,  effort: low }" "tester:      { model: haiku,  effort: high }")"; yaml
expect 1 "replace    ~/.claude/agents/tester.md" nc generate --check
grep -q "opencode" "$T/out" && fail "--check names OpenCode files for a Claude change: $(cat "$T/out")"
grep -qx "effort: low" "$CA/tester.md" || fail "--check wrote the file"
old_inode="$(inode "$CA/tester.md")"
expect 0 "replaced   ~/.claude/agents/tester.md" nc generate
grep -qx "effort: high" "$CA/tester.md" || fail "effort not changed"
[ "$(inode "$CA/tester.md")" != "$old_inode" ] || fail "tester.md written in place, not through a temporary file and a rename"
printf '\nOne more sentence.\n' >> "$RC/roles/reviewer.md"
expect 1 "replace    ~/.claude/agents/reviewer.md" nc generate --check
expect 0 "" nc generate
echo "# by hand" >> "$OA/tester.md"
expect 1 "replace    ~/.config/opencode/agents/tester.md" nc generate --check
expect 0 "" nc generate
expect 0 "" nc generate --check
ok "--check is exit 1 with the right line after a change to models.yaml, a role file or a generated file, and writes nothing; a replaced file is a new inode"

# 5. placeholder: no OpenCode file for the role, an old one is removed, exit 0 with the reason
FREE='"TODO: openrouter/<a>/<b>:free"'; yaml
expect 1 "remove     ~/.config/opencode/agents/researcher.md" nc generate --check
expect 0 "placeholder" nc generate
grep -q "skipped    OpenCode agent researcher" "$T/out" || fail "no reason for the placeholder: $(cat "$T/out")"
[ ! -e "$OA/researcher.md" ] || fail "researcher file of a placeholder class not removed"
[ -e "$CA/researcher.md" ] || fail "the Claude file does not depend on the class"
expect 0 "placeholder" nc generate --check
FREE='"openrouter/acme/tiny-1:free"'; yaml
expect 0 "" nc generate
ok "a placeholder class gets no OpenCode file, an old one is removed, exit 0 with the reason"

# 6. a role taken out of a block loses its file in that runtime only
CC_SAVE="$CC"; CC="$(grep -v '^    tester:' <<<"$CC")"; yaml
expect 1 "remove     ~/.claude/agents/tester.md" nc generate --check
expect 0 "removed    ~/.claude/agents/tester.md" nc generate
[ ! -e "$CA/tester.md" ] && [ -e "$OA/tester.md" ] || fail "tester removed in the wrong runtime"
CC="$CC_SAVE"; yaml
expect 0 "created    ~/.claude/agents/tester.md" nc generate
ok "a role taken out of claude_code.subagents loses only its Claude file"

# 7. foreign files: backed up before replacing, other foreign files stay, GENERATED in line 3 is foreign
echo "mine" > "$CA/tester.md"
echo "mine too" > "$OA/tester.md"
echo "other" > "$CA/mine.md"
printf -- '---\nname: x\n%s\n---\n' "$GEN" > "$CA/reviewer.md"
expect 1 "back up    ~/.claude/agents/tester.md -> ~/.nc/backup/$TODAY/.claude/agents/tester.md" nc generate --check
grep -q "back up    ~/.claude/agents/reviewer.md" "$T/out" || fail "line 3 marker counted as generated: $(cat "$T/out")"
grep -q "mine.md" "$T/out" && fail "--check names a foreign file of another name"
expect 0 "backed up" nc generate
is "$(cat "$HOME/.nc/backup/$TODAY/.claude/agents/tester.md")" "mine" "backup of the foreign Claude tester"
is "$(cat "$HOME/.nc/backup/$TODAY/.config/opencode/agents/tester.md")" "mine too" "backup of the foreign OpenCode tester"
grep -q "^name: x" "$HOME/.nc/backup/$TODAY/.claude/agents/reviewer.md" || fail "line 3 file not backed up"
is "$(cat "$CA/mine.md")" "other" "foreign file of another name"
is "$(line "$CA/tester.md" 2)" "$GEN" "replaced tester"
echo "again" > "$CA/tester.md"                        # same day: the backup gets the time
expect 0 "backed up" nc generate
ls "$HOME/.nc/backup/$TODAY/.claude/agents/" | grep -Eq '^tester\.md\.[0-9]{6}$' || fail "no time suffix on a second backup"
echo "mine" > "$OA/implementer.md"                    # HOME with a trailing slash: the same backup path
HOME="$HOME/" expect 0 "backed up  ~/.config/opencode/agents/implementer.md -> ~/.nc/backup/$TODAY/.config/opencode/agents/implementer.md" nc generate
is "$(cat "$HOME/.nc/backup/$TODAY/.config/opencode/agents/implementer.md")" "mine" "backup with HOME ending in /"
rm "$CA/mine.md"
ok "foreign files of the same name are backed up (with the time on a collision, also with HOME ending in /), others stay, GENERATED in line 3 is foreign"

# 8. a target folder that is a link or lies in the repo is exit 2, nothing written
mv "$CA" "$T/agents-real" && ln -s "$T/agents-real" "$CA"
expect 2 "is a link" nc generate
expect 2 "is a link" nc generate --check
rm "$CA" && mv "$T/agents-real" "$CA"
mv "$OA" "$T/oa-real" && ln -s "$T/oa-real" "$OA"
expect 2 "is a link" nc generate
expect 2 "is a link" nc generate --check
rm "$OA" && mv "$T/oa-real" "$OA"
ln -s "$RC" "$T/repo-link"
for v in "OPENCODE_CONFIG_DIR=$RC/adapters/opencode" "XDG_CONFIG_HOME=$RC" "OPENCODE_CONFIG_DIR=$T/repo-link/x" "HOME=$RC/home"; do
  env "$v" "$RC/bin/nc" generate > "$T/out" 2> "$T/err" && fail "nc generate with $v: exit 0"
  grep -q "lies in the repo" "$T/err" || fail "nc generate with $v: $(cat "$T/out" "$T/err")"
  env "$v" "$RC/bin/nc" generate --check > "$T/out" 2> "$T/err" && fail "nc generate --check with $v: exit 0"
  grep -q "lies in the repo" "$T/err" || fail "nc generate --check with $v: $(cat "$T/err")"
done
rm "$T/repo-link"
[ ! -e "$RC/adapters/opencode/agents" ] && [ ! -e "$RC/opencode" ] && [ ! -e "$RC/x" ] && [ ! -e "$RC/home" ] || fail "nc generate wrote into the repo"
ok "a target folder that is a link (Claude or OpenCode) or lies in the repo (also through a link): exit 2"

# 9. broken settings: exit 2 and no file changed
state() { find "$HOME/.claude" "$HOME/.config" "$HOME/.nc" -exec ls -ld {} + 2>/dev/null | awk '{print $1, $5, $NF}'; cat "$CA"/* "$OA"/*; }
before="$(state)"
broken() {  # broken <pattern>: nc generate and --check refuse the current models.yaml/roles, nothing changes
  expect 2 "$1" nc generate
  expect 2 "$1" nc generate --check
  grep -q "    at " "$T/err" && fail "stack trace: $(cat "$T/err")"
  [ "$(state)" = "$before" ] || fail "files changed although nc generate refused ($1)"
}
sub() { CC="$1" OC="$2" yaml "${3:-}"; }
X="$(r "$CC" "model: sonnet" "model: gpt")"; sub "$X" "$OC";                     broken 'claude_code.subagents.implementer.model is "gpt"'
X="$(r "$CC" "effort: xhigh" "effort: extreme")"; sub "$X" "$OC";                broken 'effort is "extreme"'
X="$(r "$CC" "opus,   effort: xhigh }" "opus }")"; sub "$X" "$OC";                             broken "claude_code.subagents.reviewer.effort is not set"
X="$(r "$CC" "orchestrator: { model: opus" "orchestrator: { model: sonnet")"; sub "$X" "$OC"; broken 'claude_code.orchestrator.model is "sonnet", allowed: opus, fable'
sub "$CC
    scout:       { model: haiku, effort: low }" "$OC" ;         broken 'role "scout" is not in roles'
sub "$CC" "$OC
    planner:     {}";                                          broken "the role's class frontier has runtime: claude-code"
X="$(r "$CC" "subagents:" "subagent:")"; sub "$X" "$OC";                         broken 'claude_code has an unknown key "subagent"'
X="$(r "$OC" "variant: low" "variant: low, model: x")"; sub "$CC" "$X";         broken 'opencode.subagents.tester has an unknown key "model"'
X="$(r "$CC" "claude_code:" "claude-code:")"; sub "$X" "$OC";                    broken 'unknown key "claude-code" at the top level'
X="$(r "$OC" "variant: low" "variant: Low")"; sub "$CC" "$X";                   broken 'variant "Low" is not made of'
X="$(r "$OC" "variant: low" "variant: \"lo w\"")"; sub "$CC" "$X";              broken 'variant "lo w" is not made of'
FREE='"openrouter/acme/tiny-1:free#none"'
X="$(r "$OC" "researcher:  {}" "researcher:  { variant: thinking }")"; sub "$CC" "$X"; broken "already contains a variant"
FREE='"openrouter/acme/tiny-1:free"'; yaml
# From here on a change is pending, so a generator that writes a role right after reading it would show.
CC_SAVE="$CC"; CC="$(r "$CC" "tester:      { model: haiku,  effort: high }" "tester:      { model: haiku,  effort: medium }")"; yaml
expect 1 "replace    ~/.claude/agents/tester.md" nc generate --check
mv "$RC/roles/tester.md" "$T/tester.md.away";                   broken "role \"tester\" has no file roles/tester.md"
mv "$T/tester.md.away" "$RC/roles/tester.md"
cp "$RC/roles/planner.md" "$T/planner.md.save"
sed -i.bak 's/^name: planner$/name: plan/' "$RC/roles/planner.md";      broken 'name "plan" is not the file name'
cp "$T/planner.md.save" "$RC/roles/planner.md"
sed -i.bak 's/^access: read$/access: admin/' "$RC/roles/planner.md";    broken 'access is "admin", allowed: read, write'
cp "$T/planner.md.save" "$RC/roles/planner.md"
sed -i.bak '/^description:/d' "$RC/roles/planner.md";                   broken "description missing"
cp "$T/planner.md.save" "$RC/roles/planner.md"
sed -i.bak '1d' "$RC/roles/planner.md";                                 broken "no frontmatter"
cp "$T/planner.md.save" "$RC/roles/planner.md"
awk '{ print } /^access: read$/ { print "class: frontier" }' "$T/planner.md.save" > "$RC/roles/planner.md"; broken 'unknown field "class"'
cp "$T/planner.md.save" "$RC/roles/planner.md"
cp "$RC/roles/researcher.md" "$T/researcher.md.save"             # read last, after tester
sed -i.bak 's/^access: read$/access: admin/' "$RC/roles/researcher.md"; broken 'roles/researcher.md: access is "admin"'
cp "$T/researcher.md.save" "$RC/roles/researcher.md" && rm -f "$RC/roles/"*.bak
CC="$CC_SAVE"; yaml
expect 0 "" nc generate --check
ok "unknown model, effort, missing effort, sonnet as orchestrator, role not in roles or without a file, planner in opencode, unknown keys (block, top level), bad variant, variant on a model with #, role file name/access/description/frontmatter/unknown field (also the role read last, with a change pending): exit 2, no file changed"

# 10. model: inherit is valid
X="$(r "$CC" "model: haiku,  effort: medium" "model: inherit, effort: medium")"; sub "$X" "$OC"
expect 0 "replaced   ~/.claude/agents/researcher.md" nc generate
grep -qx "model: inherit" "$CA/researcher.md" || fail "inherit not written"
yaml && expect 0 "" nc generate
ok "model: inherit is a valid subagent model"

# 11. the current folder does not change the result (the free researcher is written from an Acme folder too)
sums() { cat "$CA"/* "$OA"/* | cksum; }
want="$(sums)"
rm -rf "$CA" "$OA"
(cd "$HOME/projects/acme/website" && expect 0 "" nc generate)
is "$(sums)" "$want" "files written from an Acme folder"
[ -e "$OA/researcher.md" ] || fail "no researcher from an Acme folder"
rm -rf "$CA" "$OA"
(cd "$HOME/sandbox" && expect 0 "" nc generate)
is "$(sums)" "$want" "files written from a free folder"
ok "the same files from an Acme folder and from a free folder"

# 12. XDG_CONFIG_HOME and OPENCODE_CONFIG_DIR: the OpenCode files go there, ~/.config/opencode/agents stays empty
rm -rf "$OA"
XDG_CONFIG_HOME="$T/xdg" expect 0 "created    $T/xdg/opencode/agents/tester.md" nc generate
[ -f "$T/xdg/opencode/agents/researcher.md" ] && [ ! -e "$OA" ] || fail "XDG_CONFIG_HOME not used"
OPENCODE_CONFIG_DIR="$T/occ" XDG_CONFIG_HOME="$T/xdg" expect 0 "" nc generate
[ -f "$T/occ/agents/tester.md" ] && [ ! -e "$OA" ] || fail "OPENCODE_CONFIG_DIR not used"
expect 0 "" nc generate
ok "XDG_CONFIG_HOME and OPENCODE_CONFIG_DIR decide the OpenCode folder"

# 13. a write error is exit 2 with one line; the next run repairs
if [ "$(id -u)" != 0 ]; then
  rm "$OA/tester.md" && chmod 555 "$OA"
  expect 2 "nc generate: ~/.config/opencode/agents/tester.md: EACCES" nc generate
  is "$(wc -l < "$T/err" | tr -d ' ')" 1 "lines on stderr for a write error"
  chmod 755 "$OA"
  expect 0 "created    ~/.config/opencode/agents/tester.md" nc generate
fi
ok "a folder that cannot be written is exit 2 with one line, a new run repairs"

# 14. wrong calls and the task container
expect 2 "unknown argument" nc generate --force
expect 2 "unknown argument" nc generate --check x
NC_HARNESS_VERSION=0123456789abcdef expect 2 "not in a task container" nc generate
NC_HARNESS_VERSION=0123456789abcdef expect 2 "not in a task container" nc generate --check
ok "unknown arguments and a call inside a task container: exit 2"

# 15. --out DIR --path PROJECT: the folder of a task container, with the policy of the project's host folder
O="$T/out-dir"; ACME="$HOME/projects/acme/website"; FREEP="$HOME/sandbox"
expect 2 "--out and --path only together" nc generate --out "$O"
expect 2 "--out and --path only together" nc generate --path "$ACME"
expect 2 "--out and --path only together" nc generate --check --out="$O"
expect 2 'is not an absolute path' nc generate --out out-dir --path "$ACME"
expect 2 'is not an absolute path' nc generate --out "$O" --path projects/acme/website
expect 2 "--out needs a value" nc generate --out= --path "$ACME"
expect 2 "--path needs a value" nc generate --out "$O" --path
expect 2 "--out given twice" nc generate --out "$O" --out "$O" --path "$ACME"
expect 2 "--check given twice" nc generate --check --check
expect 2 "unknown argument" nc generate --out "$O" --path "$ACME" --force
[ ! -e "$O" ] || fail "a wrong call created the --out folder"
expect 1 "create     $O/claude/planner.md" nc generate --check --out "$O" --path "$ACME"
[ ! -e "$O" ] || fail "--check created the --out folder"
ok "--out and --path only together, absolute, not empty, not twice (also --x=value); --check writes nothing"

# Acme: five Claude files equal to the host's, OpenCode only implementer and tester
expect 0 "" nc generate                                 # the host files as reference
expect 0 "skipped    OpenCode agent researcher: class free not allowed in $ACME" nc generate --out="$O" --path="$ACME"
